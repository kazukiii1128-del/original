# ── 헬퍼 ─────────────────────────────────────────────────────────────────────
def rt(text):
    return [{"type": "text", "text": {"content": str(text)[:2000]}}] if text else []

def safe_url(t):
    t = str(t).strip() if t else ""
    return t if t.startswith("http://") or t.startswith("https://") else None

def safe_phone(t):
    t = str(t).strip() if t else ""
    return None if not t or t.startswith("http") or "@" in t else t

def g(row, i):
    return row[i].strip() if i < len(row) else ""

